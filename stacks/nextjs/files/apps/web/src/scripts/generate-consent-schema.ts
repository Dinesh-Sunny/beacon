// Writes packages/db/src/schema/consent.ts from c15t's own schema, so consent tables go through
// our drizzle-kit migrations like every other table. Re-run after upgrading @c15t/backend, then
// `pnpm db:generate`: `pnpm --filter web consent:schema`.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { drizzleAdapter } from "@c15t/backend/db/adapters/drizzle";
import { DB } from "@c15t/backend/db/schema";

const OUTPUT = resolve(
  import.meta.dirname,
  "../../../../packages/db/src/schema/consent.ts",
);
// Postgres schema for c15t's tables, next to `auth` and `payload`.
const CONSENT_DB_SCHEMA = "consent";

// generateSchema only renders code; it never touches the database.
const { code } = DB.client(
  drizzleAdapter({ db: {}, provider: "postgresql" }),
).generateSchema("latest");

// Each rewrite must apply: if c15t changes how it emits code, fail here instead of silently
// writing tables to `public` or timestamps without a time zone.
function rewrite(
  source: string,
  pattern: RegExp,
  replacement: string | ((...match: string[]) => string),
  what: string,
): string {
  const global = new RegExp(
    pattern.source,
    pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`,
  );
  if (!global.test(source)) {
    throw new Error(
      `[consent] c15t schema output changed: no ${what} to rewrite`,
    );
  }
  global.lastIndex = 0;
  return source.replace(global, replacement as string);
}

let transformed = code;
// Tables go in the consent schema instead of public. fumadb looks tables up by export name, so
// the Postgres schema is free to choose.
transformed = rewrite(
  transformed,
  /pgTable\(/,
  "consentSchema.table(",
  "pgTable calls",
);
transformed = rewrite(
  transformed,
  /import \{ ([^}]*)\} from "drizzle-orm\/pg-core"/,
  (_match: string, names: string) => {
    const imports = names
      .split(",")
      .map((name) => name.trim())
      .filter((name) => name && name !== "pgTable");
    return `import { ${[...imports, "pgSchema"].sort().join(", ")} } from "drizzle-orm/pg-core"`;
  },
  "pg-core import",
);
// Every timestamp in our databases carries a time zone (docs/knowledge/database.md).
transformed = rewrite(
  transformed,
  /timestamp\("(\w+)"\)/,
  'timestamp("$1", { withTimezone: true })',
  "timestamp columns",
);
if (/timestamp\("\w+", \{(?![^}]*withTimezone)/.test(transformed)) {
  throw new Error("[consent] a timestamp column still lacks withTimezone");
}
// Relation callbacks destructure helpers they don't all use; Biome rejects unused params.
transformed = transformed
  .replaceAll("({ one, many }) => ({", "(r) => ({")
  .replace(/\b(one|many)\(/g, "r.$1(");

const header = `// GENERATED by apps/web/src/scripts/generate-consent-schema.ts from @c15t/backend. Do not edit;
// re-run the script after upgrading c15t, then \`pnpm db:generate\`.
`;

const withSchema = rewrite(
  transformed,
  /(import \{ relations \} from "drizzle-orm"\n)/,
  `$1\nexport const consentSchema = pgSchema("${CONSENT_DB_SCHEMA}");\n`,
  "relations import",
);

writeFileSync(OUTPUT, `${header}${withSchema}`);
// Same formatting and import order as hand-written code.
execFileSync("biome", ["check", "--write", OUTPUT], { stdio: "inherit" });
console.info(`[consent] wrote ${OUTPUT}`);
